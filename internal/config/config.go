// Package config loads and validates powcon-plus settings.
package config

import (
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/BurntSushi/toml"
)

// LabelMode selects what the panel shows next to the tray icon.
type LabelMode string

const (
	ModePower  LabelMode = "power"  // instantaneous AC power, e.g. "148 W"
	ModeEnergy LabelMode = "energy" // today's energy, e.g. "2.4 kWh"
	ModeBoth   LabelMode = "both"   // "148 W · 2.4 kWh"
	ModeNone   LabelMode = "none"   // icon only
)

// Config is the effective configuration of the daemon.
type Config struct {
	// hwmon sensor. Empty = auto-detect the PSU chip (name == "corsairpsu").
	Sensor string `toml:"sensor"`

	// Sampling rate. The PSU HID device answers in bursts: below 250ms makes no sense.
	PollInterval Duration `toml:"poll_interval"`

	// What to show in the GNOME top bar.
	LabelMode LabelMode `toml:"label_mode"`

	// Label formatting (printf, float64 argument).
	FormatW  string `toml:"format_w"`
	FormatWh string `toml:"format_wh"`

	// Tariff used for the cost estimate.
	EurPerKWh float64 `toml:"price_eur_per_kwh"`

	// Alerts: 0 = disabled. Sustain = required duration above the threshold.
	AlertPowerW  float64  `toml:"alert_power_w"`
	AlertSustain Duration `toml:"alert_sustain"`
	AlertCool    Duration `toml:"alert_cooldown"`

	// Persistence.
	DataDir       string   `toml:"data_dir"`
	SampleStore   bool     `toml:"sample_store"`    // JSONL log of samples
	SampleEvery   Duration `toml:"sample_interval"` // how often to write a sample
	RetentionDays int      `toml:"retention_days"`  // days of samples to keep

	// Behaviour.
	SingleInstance bool `toml:"single_instance"`
	StartWindow    bool `toml:"start_window"` // opens the window alongside the daemon

	// Icon: "pixmap" (generated by the program, always visible) or a theme icon name.
	IconMode string `toml:"icon_mode"`
	IconName string `toml:"icon_name"`
}

// Duration is a JSON/TOML-friendly wrapper around time.Duration.
type Duration struct{ time.Duration }

// UnmarshalText implements encoding.TextUnmarshaler for TOML.
func (d *Duration) UnmarshalText(text []byte) error {
	v, err := time.ParseDuration(string(text))
	if err != nil {
		return err
	}
	d.Duration = v
	return nil
}

// MarshalText implements encoding.TextMarshaler.
func (d Duration) MarshalText() ([]byte, error) {
	return []byte(d.Duration.String()), nil
}

// Default returns the factory configuration.
func Default() Config {
	return Config{
		Sensor:         "",
		PollInterval:   Duration{time.Second},
		LabelMode:      ModePower,
		FormatW:        "%.0f W",
		FormatWh:       "%.2f kWh",
		EurPerKWh:      0.25,
		AlertPowerW:    0,
		AlertSustain:   Duration{15 * time.Second},
		AlertCool:      Duration{5 * time.Minute},
		DataDir:        "",
		SampleStore:    true,
		SampleEvery:    Duration{10 * time.Second},
		RetentionDays:  31,
		SingleInstance: true,
		StartWindow:    false,
		IconMode:       "pixmap",
		IconName:       "powersupply",
	}
}

// Path returns the path of the user configuration file.
func Path() string {
	if p := os.Getenv("POWCON_CONFIG"); p != "" {
		return p
	}
	cfg, err := os.UserConfigDir()
	if err != nil {
		cfg = "."
	}
	return filepath.Join(cfg, "powcon-plus", "config.toml")
}

// Load reads the file (defaults apply when it is missing) and applies environment overrides.
func Load(path string) (Config, error) {
	c := Default()
	if path == "" {
		path = Path()
	}
	if _, err := os.Stat(path); err == nil {
		if _, err := toml.DecodeFile(path, &c); err != nil {
			return c, fmt.Errorf("lettura %s: %w", path, err)
		}
	} else if !os.IsNotExist(err) {
		return c, err
	}

	if v := os.Getenv("POWCON_SENSOR"); v != "" {
		c.Sensor = v
	}
	if v := os.Getenv("POWCON_DATA_DIR"); v != "" {
		c.DataDir = v
	}
	if v := os.Getenv("POWCON_LABEL_MODE"); v != "" {
		c.LabelMode = LabelMode(v)
	}
	if c.DataDir == "" {
		st, err := os.UserHomeDir()
		if err != nil {
			return c, err
		}
		c.DataDir = filepath.Join(st, ".local", "share", "powcon-plus")
	}
	if err := c.Validate(); err != nil {
		return c, err
	}
	return c, nil
}

// Validate normalizes and checks the values.
func (c *Config) Validate() error {
	if c.PollInterval.Duration <= 0 {
		c.PollInterval.Duration = time.Second
	}
	if c.PollInterval.Duration < 200*time.Millisecond {
		c.PollInterval = Duration{200 * time.Millisecond}
	}
	switch c.LabelMode {
	case ModePower, ModeEnergy, ModeBoth, ModeNone:
	default:
		return fmt.Errorf("label_mode %q non valido (power|energy|both|none)", c.LabelMode)
	}
	if c.EurPerKWh < 0 {
		c.EurPerKWh = 0
	}
	if c.RetentionDays < 0 {
		c.RetentionDays = 0
	}
	if c.AlertSustain.Duration <= 0 {
		c.AlertSustain = Duration{10 * time.Second}
	}
	if c.AlertCool.Duration <= 0 {
		c.AlertCool = Duration{5 * time.Minute}
	}
	if c.IconMode != "pixmap" && c.IconMode != "name" {
		c.IconMode = "pixmap"
	}
	if c.FormatW == "" {
		c.FormatW = "%.0f W"
	}
	if c.FormatWh == "" {
		c.FormatWh = "%.2f kWh"
	}
	return nil
}

// WriteSample writes a sample file, used by `powcon-plus init-config`.
func WriteSample(path string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	c := Default()
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		if os.IsExist(err) {
			return fmt.Errorf("%s esiste già", path)
		}
		return err
	}
	defer f.Close()
	fmt.Fprintf(f, "# powcon-plus — configurazione\n")
	fmt.Fprintf(f, "# sensore hwmon (vuoto = auto-detect del PSU Corsair)\n")
	if err := toml.NewEncoder(f).Encode(c); err != nil {
		return err
	}
	return nil
}

// Save writes the configuration (overwrites the file).
func Save(path string, c Config) error {
	if path == "" {
		path = Path()
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o644)
	if err != nil {
		return err
	}
	if _, err := f.WriteString("# powcon-plus — configurazione\n"); err != nil {
		f.Close()
		return err
	}
	if err := toml.NewEncoder(f).Encode(c); err != nil {
		f.Close()
		os.Remove(tmp)
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
